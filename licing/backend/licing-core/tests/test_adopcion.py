import pytest
from sqlalchemy import inspect, text
from sqlalchemy.exc import ProgrammingError

from app.adopcion import REVISION_ACTUAL, registrar_esquema, verificar_esquema


def test_verificacion_sin_modificaciones(integration_db):
    connection = integration_db.connection()
    antes = connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    assert verificar_esquema(connection) == []
    assert connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one() == antes


def test_adopta_tablas_manuales_y_conserva_datos_y_usuarios(integration_db):
    connection = integration_db.connection()
    connection.execute(text("DROP TABLE public.alembic_version"))
    connection.execute(text("CREATE TABLE public.usuario (id integer PRIMARY KEY, nombre text NOT NULL)"))
    connection.execute(text("INSERT INTO public.usuario VALUES (1, 'Cuenta existente')"))
    connection.execute(text("ALTER TABLE public.usuario ENABLE ROW LEVEL SECURITY"))
    connection.execute(text("CREATE POLICY perfil_existente ON public.usuario FOR SELECT USING (true)"))
    raw_id = connection.execute(text("""
        INSERT INTO raw_mercado_publico (fuente,tipo_consulta,codigo_externo,respuesta,http_status,consultado_en)
        VALUES ('licitaciones','detalle_codigo','TEST-ADOPCION','{}',200,now()) RETURNING id
    """)).scalar_one()
    connection.execute(text("INSERT INTO licitacion (codigo_externo,raw_id,nombre) VALUES ('TEST-ADOPCION',:raw_id,'Registro existente')"), {"raw_id": raw_id})

    registrar_esquema(connection)

    assert connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one() == REVISION_ACTUAL
    assert connection.execute(text("SELECT nombre FROM licitacion WHERE codigo_externo='TEST-ADOPCION'")).scalar_one() == "Registro existente"
    assert connection.execute(text("SELECT nombre FROM usuario")).scalar_one() == "Cuenta existente"
    assert connection.execute(text("SELECT count(*) FROM pg_policies WHERE tablename='usuario' AND policyname='perfil_existente'")).scalar_one() == 1
    assert verificar_esquema(connection) == []


def test_no_registra_esquema_con_restriccion_faltante(integration_db):
    connection = integration_db.connection()
    connection.execute(text("DROP TABLE public.alembic_version"))
    connection.execute(text("ALTER TABLE licitacion_item DROP CONSTRAINT uq_licitacion_item_correlativo"))
    assert verificar_esquema(connection)
    with pytest.raises(ValueError, match="El esquema no coincide"):
        registrar_esquema(connection)
    assert not inspect(connection).has_table("alembic_version", schema="public")


def test_no_registra_id_sin_generador(integration_db):
    connection = integration_db.connection()
    connection.execute(text("ALTER TABLE raw_mercado_publico ALTER COLUMN id DROP DEFAULT"))
    assert any("generador" in error for error in verificar_esquema(connection))


def test_acepta_identity_de_table_editor(integration_db):
    connection = integration_db.connection()
    connection.execute(text("ALTER TABLE raw_mercado_publico ALTER COLUMN id DROP DEFAULT"))
    connection.execute(text("ALTER TABLE raw_mercado_publico ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"))
    assert verificar_esquema(connection) == []


def test_rechaza_historial_desconocido(integration_db):
    connection = integration_db.connection()
    connection.execute(text("UPDATE alembic_version SET version_num='version-manual'"))
    with pytest.raises(ValueError, match="otra versión"):
        registrar_esquema(connection)
    assert connection.execute(text("SELECT version_num FROM alembic_version")).scalar_one() == "version-manual"


def test_rls_core_activa(integration_db):
    connection = integration_db.connection()
    tablas = connection.execute(text("""
        SELECT relname, relrowsecurity FROM pg_class
        WHERE relnamespace='public'::regnamespace
        AND relname IN ('raw_mercado_publico','licitacion','licitacion_item','ejecucion_ingesta','alembic_version')
    """)).all()
    assert len(tablas) == 5
    assert all(activada for nombre, activada in tablas)


@pytest.mark.parametrize("rol", ["anon", "authenticated"])
def test_roles_publicos_no_leen_ni_escriben_core(integration_db, rol):
    connection = integration_db.connection()
    if not connection.execute(text("SELECT 1 FROM pg_roles WHERE rolname=:rol"), {"rol": rol}).scalar():
        pytest.skip("Este PostgreSQL de pruebas no tiene los roles de Supabase")
    # Incluso con permisos de tabla, RLS impide acceder a filas por la Data API.
    connection.execute(text(f"GRANT SELECT, INSERT ON public.licitacion TO {rol}"))
    raw_id = connection.execute(text("""
        INSERT INTO raw_mercado_publico (fuente,tipo_consulta,respuesta,http_status,consultado_en)
        VALUES ('licitaciones','detalle_codigo','{}',200,now()) RETURNING id
    """)).scalar_one()
    connection.execute(text("INSERT INTO licitacion (codigo_externo,raw_id) VALUES ('TEST-RLS',:id)"), {"id": raw_id})
    assert connection.execute(text("SELECT count(*) FROM licitacion")).scalar_one() == 1
    connection.execute(text(f"SET LOCAL ROLE {rol}"))
    assert connection.execute(text("SELECT count(*) FROM licitacion")).scalar_one() == 0
    with pytest.raises(ProgrammingError):
        with connection.begin_nested():
            connection.execute(text("INSERT INTO licitacion (id,codigo_externo,raw_id) VALUES (999999999,'TEST-BLOQUEADO',:id)"), {"id": raw_id})
    connection.execute(text("RESET ROLE"))

